import { describe, expect, it } from 'vitest';
import { extractTrackInfo, isProbeResultMessage, PROBE_RESULT } from '../src/youtube/track-probe';

// Shape modeled on YouTube's player response; field names are not a documented API.
const RESPONSE = {
  videoDetails: { videoId: 'AAAAAAAAAAA' },
  captions: {
    playerCaptionsTracklistRenderer: {
      captionTracks: [
        { baseUrl: 'https://example.invalid/x', name: { simpleText: 'English' }, vssId: '.en', languageCode: 'en', isTranslatable: true },
        { baseUrl: 'https://example.invalid/y', name: { runs: [{ text: 'English (auto-generated)' }] }, vssId: 'a.en', languageCode: 'en', kind: 'asr' },
      ],
      translationLanguages: [{}, {}, {}],
    },
  },
};

describe('extractTrackInfo', () => {
  it('extracts metadata and never exposes baseUrl', () => {
    const r = extractTrackInfo(RESPONSE, 'movie_player.getPlayerResponse');
    expect(r.ok).toBe(true);
    expect(r.responseVideoId).toBe('AAAAAAAAAAA');
    expect(r.translationLanguageCount).toBe(3);
    expect(r.tracks).toEqual([
      { languageCode: 'en', name: 'English', kind: null, isAutoGenerated: false, vssId: '.en', isTranslatable: true, hasBaseUrl: true },
      { languageCode: 'en', name: 'English (auto-generated)', kind: 'asr', isAutoGenerated: true, vssId: 'a.en', isTranslatable: false, hasBaseUrl: true },
    ]);
    expect(JSON.stringify(r)).not.toContain('example.invalid');
  });

  it('no-caption video: ok with zero tracks', () => {
    const r = extractTrackInfo({ videoDetails: { videoId: 'B' } }, 'ytInitialPlayerResponse');
    expect(r).toMatchObject({ ok: true, tracks: [], translationLanguageCount: 0 });
  });

  it('missing / garbage player response', () => {
    expect(extractTrackInfo(undefined, 'none')).toMatchObject({ ok: false, error: 'no player response' });
    expect(extractTrackInfo({ captions: { playerCaptionsTracklistRenderer: { captionTracks: [null, 5, 'x'] } } }, 'none').tracks).toEqual([]);
  });
});

describe('isProbeResultMessage', () => {
  it('requires matching type, nonce and result shape', () => {
    const result = { ok: true, tracks: [] };
    expect(isProbeResultMessage({ type: PROBE_RESULT, nonce: 'n1', result }, 'n1')).toBe(true);
    expect(isProbeResultMessage({ type: PROBE_RESULT, nonce: 'n2', result }, 'n1')).toBe(false);
    expect(isProbeResultMessage({ type: 'other', nonce: 'n1', result }, 'n1')).toBe(false);
    expect(isProbeResultMessage({ type: PROBE_RESULT, nonce: 'n1', result: { ok: 'yes' } }, 'n1')).toBe(false);
    expect(isProbeResultMessage(null, 'n1')).toBe(false);
  });
});
